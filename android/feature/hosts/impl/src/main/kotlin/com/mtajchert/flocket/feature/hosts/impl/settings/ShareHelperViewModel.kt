/** Reads the bundled `protocol/tools` files (assets generated by the `syncFlocketShareAssets` task). */
fun interface AssetReader {
    fun read(name: String): ByteArray
}

@Module
@InstallIn(SingletonComponent::class)
object ShareHelperModule {
    @Provides
    fun assetReader(
        @ApplicationContext context: Context,
    ): AssetReader = AssetReader { name -> context.assets.open(name).use { it.readBytes() } }
}

const val HELPER_ASSET = "flocket-share"
const val INSTRUCTION_ASSET = "agent-instruction.md"

/** Status of `flocket-share` on one machine. */
sealed interface HelperStatus {
    data object Checking : HelperStatus

    data class Installed(
        val path: String,
        /** False when a login shell cannot find it (`~/.local/bin` is not on PATH). Null: not checked. */
        val onPath: Boolean? = null,
    ) : HelperStatus

    data object NotInstalled : HelperStatus

    data object Installing : HelperStatus

    /** The install was cut off after it was sent: the file may or may not be there. */
    data object MayNotBeInstalled : HelperStatus

    data class Unknown(
        val error: UiError,
    ) : HelperStatus
}

/** [machine] is null for the host itself. */
data class HelperRow(
    val machine: String?,
    val status: HelperStatus = HelperStatus.Checking,
)

data class ShareHelperUiState(
    /** False: no live session, so nothing can be checked ("Connect to check"). */
    val online: Boolean = false,
    val rows: List<HelperRow> = emptyList(),
    val instruction: String = "",
)

@HiltViewModel(assistedFactory = ShareHelperViewModel.Factory::class)
class ShareHelperViewModel
    @AssistedInject
    constructor(
        @Assisted hostId: String,
        private val connections: ConnectionManager,
        private val assets: AssetReader,
    ) : ViewModel() {
        @AssistedFactory
        interface Factory {
            fun create(hostId: String): ShareHelperViewModel
        }

        private val id = HostId(hostId)

        private fun instructionText() =
            runCatching { assets.read(INSTRUCTION_ASSET).decodeToString().trim() }.getOrDefault("")

        private val local =
            MutableStateFlow(
                ShareHelperUiState(
                    instruction = instructionText(),
                ),
            )
        val uiState: StateFlow<ShareHelperUiState> = local

        init {
            viewModelScope.launch {
                connections.overview
                    .map { list ->
                        val session = list.firstOrNull { it.host.id == id }?.session
                        val online = session?.connection is ConnectionState.Online
                        online to (if (online) session!!.machines.map { it.name } else emptyList())
                    }.distinctUntilChanged()
                    .collect { (online, machines) -> onSessionChanged(online, machines) }
            }
        }

        /** Asks the manager to connect (the host may have auto-connect off); the check runs once it is online. */
        fun connect() = connections.connect(id)

        fun recheck() {
            val machines = local.value.rows.map { it.machine }
            startRound { machines.forEach { check(it) } }
        }

        fun install(machine: String?) {
            viewModelScope.launch { runInstall(machine) }
        }

        /** One round of checks at a time: a new session state supersedes the previous round. */
        private var round: Job? = null

        private fun startRound(block: suspend () -> Unit) {
            round?.cancel()
            round = viewModelScope.launch { block() }
        }

        private fun onSessionChanged(
            online: Boolean,
            machines: List<String>,
        ) {
            val names = listOf<String?>(null) + machines
            local.update { st ->
                st.copy(
                    online = online,
                    rows = if (online) names.map { n -> HelperRow(n) } else st.rows,
                )
            }
            round?.cancel()
            if (online) startRound { names.forEach { n -> check(n) } }
        }

        private fun set(
            machine: String?,
            status: HelperStatus,
        ) = local.update { st ->
            st.copy(rows = st.rows.map { if (it.machine == machine) it.copy(status = status) else it })
        }

        private fun session(): CoreSession? = connections.session(id)

        /** Reads the status, plus the login-shell PATH check when installed. */
        private suspend fun check(machine: String?): HelperStatus {
            set(machine, HelperStatus.Checking)
            val session = session() ?: return HelperStatus.Checking
            val status =
                when (val r = session.exec(machine, STATUS_ARGV, mutating = false)) {
                    is AppResult.Failure -> {
                        HelperStatus.Unknown(r.error.toUiError())
                    }

                    is AppResult.Success -> {
                        val path =
                            r.value.stdout
                                .decodeToString()
                                .trim()
                        if (r.value.code == 0 && path.isNotEmpty()) {
                            HelperStatus.Installed(path)
                        } else {
                            HelperStatus.NotInstalled
                        }
                    }
                }
            if (status is HelperStatus.Installed) {
                // Only a completed login-shell check that finds nothing is a PATH problem; a failed check says nothing.
                val login = session.exec(machine, LOGIN_PATH_ARGV, mutating = false)
                val onPath = (login as? AppResult.Success)?.let { it.value.code == 0 }
                set(machine, status.copy(onPath = onPath))
                return status.copy(onPath = onPath)
            }
            set(machine, status)
            return status
        }

        private suspend fun runInstall(machine: String?) {
            val session = session() ?: return
            if (session.state.value.isStale) return
            set(machine, HelperStatus.Installing)
            val home =
                when (val r = session.homeDirectory(machine)) {
                    is AppResult.Failure -> return set(machine, HelperStatus.Unknown(r.error.toUiError()))
                    is AppResult.Success -> r.value.trimEnd('/')
                }
            val path = "$home/.local/bin/flocket-share"
            val bytes = withContext(Dispatchers.IO) { assets.read(HELPER_ASSET) }
            // `file.write` creates the missing folders. Mutations are never retried: an unknown outcome stops here.
            when (val w = session.writeFile(machine, path, bytes)) {
                is AppResult.Failure -> return set(machine, failure(w.error))
                is AppResult.Success -> Unit
            }
            when (val c = session.exec(machine, listOf("chmod", "755", path), mutating = true)) {
                is AppResult.Failure -> {
                    return set(machine, failure(c.error))
                }

                is AppResult.Success -> {
                    if (c.value.code != 0) {
                        val cause = IllegalStateException(c.value.stderr)
                        return set(machine, HelperStatus.Unknown(AppError.Unexpected(cause).toUiError()))
                    }
                }
            }
            check(machine)
        }

        private fun failure(error: AppError): HelperStatus =
            if (error is AppError.OutcomeUnknown) {
                HelperStatus.MayNotBeInstalled
            } else {
                HelperStatus.Unknown(error.toUiError())
            }

        companion object {
            /** `(command -v ... || test -x ...)` semantics: found on PATH, else the default install folder. */
            val STATUS_ARGV =
                listOf(
                    "sh",
                    "-c",
                    "command -v flocket-share || { test -x \"\$HOME/.local/bin/flocket-share\" && " +
                        "echo \"\$HOME/.local/bin/flocket-share\"; }",
                )
            val LOGIN_PATH_ARGV = listOf("sh", "-lc", "command -v flocket-share")
        }
    }
